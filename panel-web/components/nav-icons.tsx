const CAPABILITY_ACRONYMS = new Set(["crm", "erp", "bpm"]);

export function capabilityLabel(capability: string) {
  const value = capability.trim();
  return CAPABILITY_ACRONYMS.has(value.toLowerCase()) ? value.toUpperCase() : value;
}
